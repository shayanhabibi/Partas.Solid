/// Renders `AriaAttributes.fs` and `Svg.fs` from the ARIA and SVG members of the emission, and reads the DOM event
/// types that Xantham.Fable.Core.TS declares.
module Partas.Solid.JsxGen.ProfilesEmit

open System
open System.IO
open System.Text
open System.Text.RegularExpressions
open Partas.Solid.JsxGen.Surface
open Partas.Solid.JsxGen.Emit

/// Types nested in `Fable.Core.TS.Dom` (Xantham.Fable.Core.TS): the event types a handler can name as `Dom.<E>`.
let domTypes (dll: string) =
    use stream = File.OpenRead dll
    use pe = new System.Reflection.PortableExecutable.PEReader(stream)
    let md = System.Reflection.Metadata.PEReaderExtensions.GetMetadataReader pe

    md.TypeDefinitions
    |> Seq.choose (fun h ->
        let t = md.GetTypeDefinition h
        let parent = t.GetDeclaringType()

        // `Fable.Core.TS` is a module, so `Dom` is nested in the `TS` class rather than in a namespace.
        if not parent.IsNil && md.GetString(md.GetTypeDefinition(parent).Name) = "Dom" then
            Some(md.GetString t.Name)
        else
            None)
    |> Set.ofSeq

let private header = "// <auto-generated> tools/JsxGen from @solidjs/web's JSX declarations. Regenerate; do not edit. </auto-generated>"

let private escape (text: string) =
    text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")

let private docs (line: string -> unit) (indent: string) (text: string) =
    if text <> "" then
        line $"{indent}/// <summary>"

        for docLine in text.Replace("\r", "").Split('\n') do
            line ($"{indent}/// {escape docLine}".TrimEnd())

        line $"{indent}/// </summary>"

let private property (line: string -> unit) (m: EmittedMember) =
    match m.Injection with
    | Some args -> line $"        [<Erase; LanguageInjection({args})>]"
    | None -> line "        [<Erase>]"

    line $"        member _.{memberIdentifier m.Identifier}"
    line $"            with set (_: {m.Type}) = ()"
    line $"            and [<Erase>] get (): {m.Type} = unbox ()"
    line ""

/// `module Aria`: ARIA attributes as camelCase members on `HtmlTag`. The plugin writes `aria-` + the lowercased rest,
/// and turns `bool` values of ARIA's "true"/"false" states into those strings.
let renderAria (emission: Emission) =
    let out = StringBuilder()
    let line (text: string) = out.Append(text).Append('\n') |> ignore
    line header
    line "namespace Partas.Solid"
    line ""
    line "open Fable.Core"
    line "open Fable.Core.TS"
    line "open JetBrains.Annotations"
    line "open Partas.Solid.Experimental.U"
    line ""
    line "module Aria ="
    line "    type HtmlTag with"

    for m in emission.Members |> List.filter (fun m -> m.Profile = Aria) |> List.sortBy _.Identifier do
        docs line "        " m.Docs
        property line m

    out.ToString()

/// The F# spelling of an SVG attribute that is not an identifier (`stroke-width`, `xmlns:xlink`): camelCase.
let private camel (name: string) =
    let parts = Regex.Split(name, "[-:]") |> Array.filter ((<>) "")
    parts[0] + (parts[1..] |> Array.map (fun p -> string (Char.ToUpperInvariant p[0]) + p.Substring 1) |> String.concat "")

let private isIdentifier (name: string) = Regex.IsMatch(name, "^[A-Za-z_][A-Za-z0-9_]*$")

/// `alignment-baseline` -> `alignmentbaselineAttributeInterfaceProvider`, the existing scheme.
let private provider (name: string) =
    name.Replace("-", "").Replace(":", "") + "AttributeInterfaceProvider"

/// `Svg.fs`: one provider interface per attribute that several SVG interfaces declare, the SVG interfaces inheriting
/// their bases and providers, the members, and `module Svg` with the tags. Hyphenated attributes are hidden members
/// with a camelCase alias.
let renderSvg (surface: Surface) (emission: Emission) (existingSvg: string) =
    let svg = emission.Members |> List.filter (fun m -> m.Profile = Svg)
    let byName = surface.Interfaces |> Array.map (fun i -> i.Name, i) |> Map.ofArray
    let svgInterfaces = svg |> List.map _.Target |> List.distinct |> Set.ofList

    let allSvgInterfaces =
        surface.Interfaces
        |> Array.filter (fun i -> i.Name.Contains "SVG" && i.Name.EndsWith "Attributes")
        |> Array.map _.Name
        |> Set.ofArray
        |> Set.union svgInterfaces

    let shared =
        svg
        |> List.groupBy _.Name
        |> List.filter (fun (_, uses) -> (uses |> List.map _.Target |> List.distinct |> List.length) > 1)
        |> List.map fst
        |> Set.ofList

    let out = StringBuilder()
    let line (text: string) = out.Append(text).Append('\n') |> ignore
    line header
    line "namespace Partas.Solid"
    line ""
    line "open Fable.Core"
    line "open Fable.Core.TS"
    line "open JetBrains.Annotations"
    line "open Partas.Solid.Experimental.U"
    line ""

    for name in shared do
        line $"/// <summary>Providing the attribute <c>{name}</c> to the interfaces that share it.</summary>"
        line "[<AllowNullLiteral; EB(EBState.Never)>]"
        line $"type {provider name} = interface end"
        line ""

    // Bases first: an interface can only inherit one declared above it.
    let basesOf (name: string) =
        byName.TryFind name
        |> Option.map (fun i -> i.Bases |> Array.filter allSvgInterfaces.Contains |> Array.toList)
        |> Option.defaultValue []

    let ordered =
        let rec visit (seen: string list) (name: string) =
            if List.contains name seen then seen else name :: (basesOf name |> List.fold visit seen)

        allSvgInterfaces |> Set.toList |> List.fold visit [] |> List.rev

    for name in ordered do
        let providers =
            svg
            |> List.filter (fun m -> m.Target = name && shared.Contains m.Name)
            |> List.map (fun m -> provider m.Name)
            |> List.distinct

        line "[<AllowNullLiteral>]"
        line "[<Interface; EB(EBState.Never)>]"

        match basesOf name @ providers with
        | [] -> line $"type {name} = interface end"
        | inherits ->
            line $"type {name} ="

            for i in inherits do
                line $"    inherit {i}"

        line ""

    let member' (m: EmittedMember) =
        docs line "        " m.Docs

        if isIdentifier m.Name then
            line "        [<Erase>]"
            line $"        member _.{memberIdentifier m.Name}"
            line $"            with set (_: {m.Type}) = ()"
            line $"            and [<Erase>] get (): {m.Type} = unbox ()"
        else
            line "        [<Erase; EB(EBState.Never)>]"
            line $"        member _.``{m.Name}``"
            line $"            with set (_: {m.Type}) = ()"
            line $"            and [<Erase>] get (): {m.Type} = unbox ()"
            line ""
            line "        [<Erase>]"
            line $"        member this.{camel m.Name}"
            line $"            with inline set (value: {m.Type}) = this.``{m.Name}`` <- value"
            line $"            and inline get (): {m.Type} = this.``{m.Name}``"

        line ""

    line "[<Erase; AutoOpen>]"
    line "module AttributeExtensions ="

    for name in shared do
        line $"    type {provider name} with"
        member' (svg |> List.find (fun m -> m.Name = name))

    for target, members in svg |> List.filter (fun m -> not (shared.Contains m.Name)) |> List.groupBy _.Target do
        line $"    type {target} with"

        for m in members |> List.distinctBy _.Name do
            member' m

    // Tags: existing identifiers stay (`use'`), new ones follow the keyword rule.
    let existing =
        let cut = existingSvg.IndexOf "module Svg ="

        if cut < 0 then
            Map.empty
        else
            Regex.Matches(existingSvg.Substring cut, @"type ([\w'`-]+)\(\) =")
            |> Seq.map (fun m -> m.Groups[1].Value.Trim('`').TrimEnd('\''), m.Groups[1].Value)
            |> Map.ofSeq

    line "[<Erase>]"
    line "module Svg ="

    for tag in surface.Tags |> Array.filter (fun t -> t.Group = "svg") do
        line "    [<Erase>]"
        line $"    type {existing.TryFind tag.Name |> Option.defaultValue (memberIdentifier tag.Name)}() ="
        line "        interface RegularNode"

        for i in tag.Interfaces do
            line $"        interface {i}"

        line ""

    out.ToString()
